// Собирает короткое описание проекта (markdown) из тех же данных, что прототип и ТЗ.
// Запуск: node build_md.js <файл прототипа> <файл .md>
const fs = require('fs');
const [src, out] = process.argv.slice(2);
const html = fs.readFileSync(src, 'utf8');
const data = html.slice(html.indexOf('const PROJECT = {'), html.indexOf('/* =====================================================================\n   ПРОТОТИП'));
const { PROJECT, STATUS, STATES, BLOCKS, ACTS, BOOSTERS, GROUPS, MECH, QUESTIONS, TIMING } =
  new Function(data + '; return { PROJECT, STATUS, STATES, BLOCKS, ACTS, BOOSTERS, GROUPS, MECH, QUESTIONS, TIMING };')();

const dm = iso => iso.slice(8, 10) + '.' + iso.slice(5, 7);
const range = (a, b) => a === b ? dm(a) : `${dm(a)}–${dm(b)}`;
const plural = (n, one, few, many) => { const m = n % 100, k = n % 10; return m > 10 && m < 20 ? many : k === 1 ? one : k > 1 && k < 5 ? few : many; };
const wPl = n => plural(n, 'удовольствие', 'удовольствия', 'удовольствий');
const plMax = a => (a.pl || 0) * (a.max || 1);
const blockMax = id => ACTS.filter(a => a.block === id).reduce((s, a) => s + plMax(a), 0);
const total = ACTS.reduce((s, a) => s + plMax(a), 0);
const title = id => ACTS.find(a => a.id === id).title;
const pts = a => {
  const p = a.pts;
  if (p.kind === 'fixed') return p.v ? `${p.v}` : '—';
  if (p.kind === 'score') return `до ${p.v}, по верным ответам`;
  if (p.kind === 'result') return `${p.v} за рубеж, в рейтинг — лучший результат`;
  if (p.kind === 'bonus') return `бонус ${p.v} первым N нашедшим`;
  if (p.kind === 'tries') return `${p.v} с первой попытки / ${p.v2} со второй`;
  return '—';
};
const when = a => a.to ? range(a.from, a.to) : `с ${dm(a.from)}`;
const pl = a => !a.pl ? '—' : a.max > 1 ? `${a.pl} × до ${a.max} раз` : `${a.pl}`;
const st = a => STATUS[a.status].label.toLowerCase();
const cell = s => String(s).replace(/\|/g, '/');

const L = [];
const p = (...x) => L.push(...x);

p(`# ${PROJECT.title} — описание проекта`, '',
  `*Версия ${PROJECT.version} от ${PROJECT.updated}. Собрано из прототипа и ТЗ: https://vasilievanton.github.io/mts33-prototype/*`, '',
  `Онлайн-платформа с заданиями для сотрудников МТС и дочерних компаний к 33-летию компании и страница онлайн-эфира. Концепция — «33 года — все 33 удовольствия»: участник собирает ${PROJECT.pleasuresTotal} «удовольствия» — отметки о выполнении заданий. Участник выбирает раздел, в разделе — активность, внутри активности проходит её задания. Прогресс виден в шапке, рядом турнирная таблица. Визуальный образ — новый KV в работе. Эфир ${dm(PROJECT.stream)} — «34-е удовольствие», которое нельзя получить на платформе.`, '',
  'Статусы в тексте: **согласовано** — можно брать в работу; **на согласовании** — ждём решения МТС; **допущение** — наша заглушка, нужно утвердить.', '');

p('## 1. Базовые настройки', '',
  `- **Период:** ${dm(PROJECT.start)}–${dm(PROJECT.end)} — неделя до эфира и две после, эфир — ${dm(PROJECT.stream)}. Все даты — по Москве.`,
  '- **Участники:** сотрудники МТС и дочерних компаний, до 20 000 человек. Компьютер и телефон (браузер).',
  `- **Цель участника:** собрать все ${PROJECT.pleasuresTotal} удовольствия и набрать баллы для турнирной таблицы. Сейчас в реестре — ${total} из ${PROJECT.pleasuresTotal}${total === PROJECT.pleasuresTotal ? '' : ' ⚠ не сходится'}.`,
  '- **Не делаем:** вход через корпоративные учётные записи, магазин призов, офлайн-часть, уведомления участникам.', '',
  '**Разделы и активности**', '', '| Раздел | Активности | Удовольствий |', '|---|---|---|',
  ...BLOCKS.map(b => `| ${b.name} | ${GROUPS.filter(g => g.block === b.id).map(g => g.title + (g.acts.length > 1 ? ` (${g.acts.length})` : '')).join(', ')} | ${blockMax(b.id)} |`), '');

p('## 2. Правила начисления', '',
  '- **Удовольствия** — отметки о выполнении, от результата не зависят. **Баллы** — для турнирной таблицы, зависят от сложности и результата. У каждого задания свои значения (см. раздел 3).',
  `- **Все ${PROJECT.pleasuresTotal} — для всех:** любой участник может собрать все удовольствия до ${dm(PROJECT.end)}, даже если пришёл в последний день. Ограничены по времени только баллы: бонус за свечку, голосования по главам, «Кто виновник?».`,
  '- **Задания открываются постепенно** и потом не закрываются. Серии (разминки, выпуски квиза) проходятся по порядку.',
  '- **Материалы участников** (истории, номера, благодарности) засчитываются после проверки организаторами. Отклонённый материал не засчитывается и не занимает лимит.',
  '- **Счастливый час** — ×2 баллов за конкретное задание в заданное окно; удовольствия не умножаются.',
  '- **Бонус за заход** — раз в неделю; ежедневных бонусов нет.',
  '- **Лайки:** автор номера баллов за полученные лайки не получает.',
  '- **Шкала баллов:** 10 — простые задания, 20 — средние, 30 — сложные и творческие, 50 — особые.', '');

p('## 3. Задания', '', '«Удовольствия» — сколько даёт одно выполнение и сколько раз его можно выполнить.', '');
BLOCKS.forEach(b => {
  const acts = ACTS.filter(a => a.block === b.id); if (!acts.length) return;
  p(`### ${b.name} — ${blockMax(b.id)} ${wPl(blockMax(b.id))}`, '',
    '| Задание | Что делает участник | Даты | Удовольствия | Баллы | Статус |', '|---|---|---|---|---|---|',
    ...acts.map(a => `| ${(g => g && g.acts.length > 1 ? cell(g.title) + ' → ' : '')(GROUPS.find(g => g.acts.includes(a.id)))}${cell(a.title)}${a.hidden ? ' (скрытое)' : ''} | ${cell(a.desc)}${a.dep ? ` После «${cell(title(a.dep))}».` : ''} | ${when(a)} | ${pl(a)} | ${cell(pts(a))} | ${st(a)} |`), '');
});

p('## 4. Как устроены задания', '');
// Коротко: по одному разделу на тип — правила начисления, если есть, иначе что делает участник
Object.entries(MECH).forEach(([k, m]) => {
  const used = ACTS.filter(a => a.type === k); if (!used.length || ['system', 'tbd'].includes(k)) return;
  const sec = m.sections.find(([t]) => t === 'Правила') || m.sections.find(([t]) => !['Статус', 'Суть'].includes(t));
  p(`- **${m.title}** — ${used.length > 2 ? used.length + ' ' + plural(used.length, 'задание', 'задания', 'заданий') : used.map(a => '«' + a.title + '»').join(', ')}. ${sec[1].join(' ')}`);
});
p('');

p('## 5. Модули платформы', '',
  '- **Лендинг** — суть праздника, место под KV, разделы, анонс эфира и призов, вход и регистрация.',
  '- **Регистрация и вход** — по корпоративной почте МТС или дочерней компании: имя, фамилия, почта, пароль, регион, компания, согласия; затем подтверждение почты кодом из письма. Забыли пароль — присылаем новый пароль на почту, без ссылок и кодов; сменить его можно в профиле.',
  '- **Главная** — разделы и турнирная таблица (топ-10 и «Ты»), баннеры счастливого часа и эфира. Прогресс «N / 33 · баллы» — только в шапке, возле аватара.',
  '- **Раздел** — карточки активностей. **Активность** — её задания вкладками (например, «Сиять» — пять разминок); открывается первое невыполненное.',
  '- **Мой прогресс** — открывается из прогресса в шапке: шесть колонок по разделам, что собрано и переход к непройденному.',
  '- **Профиль** — данные участника и «Мои материалы»: на модерации, опубликовано, отклонено.',
  '- **Турнирная таблица и призы** — топ по баллам со строкой «Ты», таблица «За что начисляются баллы». Две категории победителей: лидеры рейтинга (например, розыгрыш среди топ-100) и розыгрыш среди всех, кто набрал пороговое число баллов (условия — на согласовании).',
  `- **Онлайн-эфир** — ток-шоу «Без галстука» ${dm(PROJECT.stream)}: до эфира — отсчёт и «Добавить в календарь», в эфир — плеер и чат (если есть), после — запись. Баллы за просмотр; квизы и опросы — в плеере провайдера. План Б — прямая ссылка на трансляцию.`,
  '- **Задания-сюрпризы и счастливые часы** — неанонсированные задания и окна ×2 баллов (см. раздел 6).',
  '- **Правила акции** — коротко: в каких активностях участвовать и как разыгрываются призы; частые вопросы; ссылка на полные правила (PDF); почта для вопросов. Отдельного FAQ и формы обращения нет.',
  '- **Где участник видит результат** — только на платформе: подсказка о начислении сразу после действия, статусы заданий, «Мои материалы». Письма — только служебные (код подтверждения почты при регистрации, новый пароль при восстановлении, приглашение коллеги в волонтёрский проект).',
  '- **Финальное состояние** (после ' + dm(PROJECT.end) + ') — «Праздник завершён», личный итог, итоги розыгрышей, запись эфира; всё только для просмотра, регистрация закрыта.',
  '- **Управление для организаторов** — задания и их содержание, проверка материалов, расписание счастливых часов, свечка, главы истории, эфир, справочники (домены почты, регионы, компании, номинации, волонтёрские проекты), выгрузки для розыгрышей и отчётов.', '');

p('## 6. Сюрпризы и счастливые часы', '',
  ...ACTS.filter(a => a.block === 'common' && a.id !== 'reg').map(a => `- **${a.title}** — ${a.desc[0].toLowerCase() + a.desc.slice(1)} ${(a.notes || []).join(' ')}`),
  '- **Счастливый час** — о нём узнают только на платформе, поэтому окно длинное (рабочий вариант). Примеры расписания:',
  ...BOOSTERS.map(b => `  - ${dm(b.date)}, ${b.from}–${b.to} — ×${b.mult} за «${title(b.act)}»${b.note ? ' (' + b.note + ')' : ''}`), '');

TIMING.stages.forEach(s => { if (s.group) { const g = GROUPS.find(x => x.id === s.group); s.opens = [...new Set(g.acts.map(id => ACTS.find(x => x.id === id).from))].sort(); s.title = `${g.title} (${g.kind}) · ${s.opens.length > 3 ? dm(s.opens[0]) + '–' + dm(s.opens[s.opens.length - 1]) : s.opens.map(dm).join(', ')}`; } });
const asks = TIMING.stages.flatMap(s => s.asks.map(k => ({ ...k, stage: s.title }))).sort((x, y) => x.date < y.date ? -1 : x.date > y.date ? 1 : 0);
p('## 7. Тайминг', '',
  `- **План А:** если все сроки соблюдены — запускаемся ${dm(PROJECT.start)}. Тайминг жёсткий: если что-то не успеваем, сдвигаем запуск.`,
  `- **План Б:** если хотя бы один ключевой пункт (★) не закрыт в срок — эфир ${dm(PROJECT.stream)} идёт по прямой ссылке, платформа открывается после эфира (ориентир ${dm(TIMING.planB)}).`, '',
  '**Что и когда нужно от МТС**', '', '| Срок | Что нужно | Этап | Если не успеваем |', '|---|---|---|---|',
  ...asks.map(k => `| ${dm(k.date)} | ${k.key ? '★ ' : ''}${cell(k.what)} | ${cell(k.stage)} | ${cell(k.late)} |`), '');

const NST = { none: '—', need: 'нужно', wait: '**не хватает**', work: 'в работе', done: 'готово' };
const ncell = c => c.st === 'none' ? '—' : `${NST[c.st]}${c.due ? ' к ' + dm(c.due) : ''}: ${cell(c.t)}`;
p('**Готовность по активностям**', '', '| Активность | Открывается | Дизайн | Контент | Разработка | Решение МТС |', '|---|---|---|---|---|---|',
  ...GROUPS.filter(g => TIMING.acts[g.id]).map(g => { const n = TIMING.acts[g.id]; const o = [...new Set(g.acts.map(id => ACTS.find(a => a.id === id).from))].sort().map(dm).join(', ');
    return `| ${g.title} | ${o} | ${ncell(n.design)} | ${ncell(n.content)} | ${ncell(n.dev)} | ${ncell(n.mts)} |`; }), '');

p('## 8. Открытые вопросы', '', '**К МТС**', '', ...QUESTIONS.filter(q => q.to === 'client').map((q, i) => `${i + 1}. ${q.text}`), '',
  '**Внутри команды**', '', ...QUESTIONS.filter(q => q.to === 'team').map((q, i) => `${i + 1}. ${q.text}`), '');

fs.writeFileSync(out, L.join('\n'));
console.log(`${out}: ${L.length} строк, ${ACTS.length} заданий, ${total}/${PROJECT.pleasuresTotal} удовольствий`);
